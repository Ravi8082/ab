export function citiesInState(stateCode: string): IndiaCity[] {
  const code = stateCode.trim().toUpperCase();
  return INDIA_CITIES.filter((city) => city.state === code).sort((a, b) => a.en.localeCompare(b.en));
}

/** Google Maps search link built from whatever address parts the admin already typed. */
export function mapsSearchUrl(parts: (string | undefined)[]): string {
  const query = parts.map((part) => (part ?? '').trim()).filter(Boolean).join(', ');
  if (!query) return '';
  const url = `https://maps.google.com/?q=${encodeURIComponent(query)}`;
  return url.length <= 255 ? url : '';
}
